import { test, expect } from '@playwright/test';
test('built module workers, 300 people, search, personalized poster and self-contained export', async ({ page }) => {
  const errors = [], workers = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('worker', w => workers.push(w.url()));
  await page.route(/fonts\.googleapis|fonts\.gstatic|cdn\.jsdelivr/, r => r.abort());
  await page.goto('/?family=300#/tree-prototype');
  await expect(page.locator('[data-person]')).toHaveCount(300, { timeout: 30000 });
  expect(workers.some(url => /assets\/layout\.worker/.test(url))).toBe(true);
  expect(await page.evaluate(() => window.__layoutWorkerStats.failed)).toBe(0);
  await page.getByLabel('Search people').fill('Emma Bennett');
  await page.getByRole('button', { name: 'Emma Bennett 1984' }).click();
  await expect.poll(() => page.locator('[data-person=emma]>rect').evaluate(el => el.getBoundingClientRect().width)).toBeGreaterThan(140);
  await page.getByLabel('Branch root').selectOption('emma');
  await expect(page.locator('[data-person]')).toHaveCount(4);
  await page.getByLabel('Ancestor generations').selectOption('2');
  await expect(page.locator('[data-person]')).toHaveCount(11);
  await page.getByRole('button', { name: 'Print studio', exact: true }).click();
  await page.getByLabel('Paper size').selectOption('poster18');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download SVG', exact: true }).click();
  const file = await download;
  expect(file.suggestedFilename()).toBe('familyconnect-emma-poster18.svg');
  const stream = await file.createReadStream(), chunks = [];
  for await (const chunk of stream) chunks.push(chunk);
  const svg = Buffer.concat(chunks).toString('utf8');
  expect((svg.match(/href="data:image\/jpeg;base64,/g) || []).length).toBe(7);
  expect(errors).toEqual([]);
});

test('built premium template keeps arched portraits and recommends a readable poster',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/?family=25&template=botanical#/tree-prototype');
  await expect(page.getByTestId('print-svg').locator('[data-person]')).toHaveCount(11);
  await expect(page.locator('[data-photo]')).toHaveCount(7);
  await page.getByLabel('Premium family').selectOption('40');
  await expect(page.getByTestId('print-svg').locator('[data-person]')).toHaveCount(40);
  await expect(page.getByRole('button',{name:'Download PDF',exact:true})).toBeDisabled();
  await page.getByLabel('Paper size').selectOption('poster24');
  await expect(page.getByRole('button',{name:'Download PDF',exact:true})).toBeEnabled();
  const pending=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download SVG',exact:true}).click();
  const download=await pending, stream=await download.createReadStream(), chunks=[];
  for await(const chunk of stream)chunks.push(chunk);
  const svg=Buffer.concat(chunks).toString('utf8');
  expect(download.suggestedFilename()).toBe('familyconnect-botanical-40-poster24.svg');
  expect((svg.match(/data-person=/g)||[]).length).toBe(40);
  expect((svg.match(/href="data:image\/jpeg;base64,/g)||[]).length).toBe(8);
  expect(svg).toContain('A60 60');expect(errors).toEqual([]);
});
